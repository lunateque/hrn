//! Git and `/commit` data types shared across the TUI [`Backend`](crate::Backend) boundary.

/// Preview payload prepared by the backend for `/commit` confirmation in the TUI.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct CommitPreview {
    /// Attributed repository-relative file paths included in this commit.
    pub files: Vec<String>,
    /// Number of attributed diff hunks kept for staging.
    pub hunks_kept: usize,
    /// Number of unattributed diff hunks excluded from staging.
    pub hunks_skipped: usize,
    /// Unified diff preview of the attributed changes (including newly written files).
    pub diff_preview: String,
    /// Suggested conventional commit message generated by the `commit` role (or fallback).
    pub suggested_message: String,
    /// Whether `[commit] changelog = true` is currently configured.
    pub changelog_enabled: bool,
    /// Whether the repository contains a regular `CHANGELOG.md` file.
    pub has_changelog_file: bool,
}
